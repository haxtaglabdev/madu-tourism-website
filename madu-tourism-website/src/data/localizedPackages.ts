export function getLocalizedPackages(lang: SupportedLanguage): TourPackage[] {
  return lang === "ru" ? ruPackages : enPackages;
}

export function getLocalizedPackageDetails(lang: SupportedLanguage): PackageDetail[] {
  return lang === "ru" ? ruPackageDetails : enPackageDetails;
}

export function getLocalizedPackageBySlug(
  slug: string,
  lang: SupportedLanguage,
): PackageDetail | undefined {
  const list = getLocalizedPackageDetails(lang);
  return list.find((pkg) => pkg.slug === slug);
}

export function getLocalizedPackageDetailsPath(
  packageId: string,
  lang: SupportedLanguage,
): string | undefined {
  const match = enPackageDetails.find((pkg) => pkg.packageId === packageId);
  if (!match) return undefined;
  return lang === "ru"
    ? `/ru/tour-packages/${match.slug}`
    : `/tour-packages/${match.slug}`;
}
